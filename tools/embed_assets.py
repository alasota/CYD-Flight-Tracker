"""The settings page's CSS, JS and icon as C string literals (spec 12 stage 6, section 4.5).

The files in src/admin/assets/ are the source; src/admin/core/web_assets.h is generated from
them and checked in (only config_page.cpp includes it, so each asset is in the firmware once):

    style.css        -> kWebStyleCss        (between <style> and </style>)
    app.js           -> kWebAppJs           (after the T={...} texts from web_i18n)
    restart.js       -> kWebRestartJs       (after an update: reload once the board is back)
    check_pending.js -> kWebCheckPendingJs  (while "check now" waits)
    favicon.svg      -> kWebFaviconUri      (a data: URI in <link rel="icon">)

CSS / JS: full-line comments are dropped (`/* ... */` in CSS, also over several lines; `// ...`
in JS), every line is trimmed, empty lines are dropped and the rest is joined with nothing in
between -- so the page is byte for byte what the hand-written literals were. Three rules keep that
honest, both an error naming file:line, with nothing written:
  - a line that ends in a letter / digit / `_` / `$` / quote while the next starts with one
    (joining would glue two tokens: `return` + `x`, `margin:0` + `auto`);
  - CSS only: a line (all but the last) that doesn't end in `;`, `{`, `}` or `,` (a selector
    or a value split over two lines: `.card` + `.alert` -> `.card.alert`);
  - a comment after code on the same line (not supported; put it on its own line).
JS is checked no further here: tools/test_embed_assets.py runs `node --check` on the joined
scripts (CI has node; skipped where it's missing), which catches a `}` + `x.onerror=...` join.
Files are read as UTF-8 with an optional BOM (dropped).
SVG: `data:image/svg+xml,` + the markup without whitespace between tags, `"` -> `'` and
`#` -> `%23` (the URI sits in a double-quoted href).
The header has one C string literal per source line; only `"` and `\\` are escaped, UTF-8
(`≈ · …`) stays as it is. LF line endings, the same output for CRLF input.

Two ways to run it:
  - a PlatformIO pre-script of env:cyd and env:native (`extra_scripts`): regenerates the header
    before every build, writing it only when the content differs (no needless rebuild);
  - `python tools/embed_assets.py [--assets DIR] [--out FILE] [--check]`: the same by hand;
    `--check` exits 1 naming a stale header and writes nothing.
Importing the module (tools/test_embed_assets.py) does neither.
"""

import argparse
import re
import sys
from pathlib import Path

# (file in the assets folder, C name, kind)
ASSETS = [
    ("style.css", "kWebStyleCss", "css"),
    ("app.js", "kWebAppJs", "js"),
    ("restart.js", "kWebRestartJs", "js"),
    ("check_pending.js", "kWebCheckPendingJs", "js"),
    ("favicon.svg", "kWebFaviconUri", "svg"),
]

ASSETS_DIR = Path("src") / "admin" / "assets"
HEADER = Path("src") / "admin" / "core" / "web_assets.h"

BANNER = """\
// web_assets.h -- GENERATED by tools/embed_assets.py from src/admin/assets/: don't edit it,
// edit the asset files (the cyd and native builds regenerate this file when they differ;
// `python tools/embed_assets.py --check` reports a stale one). Only config_page.cpp includes
// it, so each asset is in the firmware once (spec 12 section 4.5).
#pragma once
"""

# A character that would join the token next to it: `return`+`x`, `0`+`auto`, `'a'`+`'b'`.
_WORD = re.compile(r"[A-Za-z0-9_$'\"]")

# What a CSS line (all but the last) may end in: the end of a declaration / block, the start of
# a block or a selector list's comma. Anything else would join a selector or a value with the
# next line (`.card` + `.alert` -> `.card.alert`, `calc(1px` + `+ 2px)`).
_CSS_ENDS = ";{},"


class EmbedError(Exception):
    """An asset the generator can't embed safely; the message names file:line."""


def _lines(text):
    return text.replace("\r\n", "\n").replace("\r", "\n").split("\n")


def _comment_outside_strings(line, starts):
    """Index of the first of `starts` (e.g. "//") outside a '...' / "..." string, or -1."""
    quote = None
    i = 0
    while i < len(line):
        ch = line[i]
        if quote:
            if ch == "\\":
                i += 2
                continue
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        elif any(line.startswith(s, i) for s in starts):
            return i
        i += 1
    return -1


def _code_lines(text, kind, name):
    """[(line number, trimmed code)] of a CSS / JS text, comment lines and empty lines dropped."""
    out = []
    in_block = False  # inside a CSS comment that spans lines
    for number, raw in enumerate(_lines(text), start=1):
        line = raw.strip()
        if in_block:
            if "*/" in line:
                if not line.endswith("*/"):
                    raise EmbedError(f"{name}:{number}: code after a comment on the same line")
                in_block = False
            continue
        if not line:
            continue
        if kind == "css" and line.startswith("/*"):
            if "*/" not in line:
                in_block = True
            elif not line.endswith("*/") or line.find("*/") != len(line) - 2:
                raise EmbedError(f"{name}:{number}: code after a comment on the same line")
            continue
        if kind == "js" and line.startswith("//"):
            continue
        starts = ("/*",) if kind == "css" else ("//", "/*")
        if _comment_outside_strings(line, starts) >= 0:
            raise EmbedError(f"{name}:{number}: a comment after code isn't supported, "
                             "put it on its own line")
        out.append((number, line))
    return out


def _pieces(text, kind, name):
    """The kept lines of a CSS / JS text, checked that joining them glues no two tokens."""
    lines = _code_lines(text, kind, name)
    for (number, line), (_, following) in zip(lines, lines[1:]):
        if kind == "css" and line[-1] not in _CSS_ENDS:
            raise EmbedError(f"{name}:{number}: a CSS line must end in ; {{ }} or , -- joined "
                             f"with nothing in between, '{line[-12:]}' + '{following[:12]}' "
                             "would change the rule")
        if _WORD.match(line[-1]) and _WORD.match(following[0]):
            raise EmbedError(f"{name}:{number}: joining this line with the next would glue "
                             f"'{line[-12:]}' to '{following[:12]}'; end or start the line "
                             "with punctuation instead")
    return [line for _, line in lines]


def embed_text(text, kind, name):
    """A CSS ("css") or JS ("js") file's text as the page carries it (see the module doc)."""
    if kind not in ("css", "js"):
        raise ValueError(f"unknown kind {kind!r}")
    return "".join(_pieces(text, kind, name))


def _svg_pieces(text):
    markup = "\n".join(_lines(text)).strip()
    markup = re.sub(r">\s+<", "><", markup)
    markup = re.sub(r"\s*\n\s*", " ", markup)
    markup = markup.replace('"', "'").replace("#", "%23")
    tags = re.split(r"(?<=>)(?=<)", markup)
    return ["data:image/svg+xml," + tags[0]] + tags[1:]


def svg_data_uri(text):
    """An SVG file as a data: URI that fits a double-quoted HTML attribute."""
    return "".join(_svg_pieces(text))


def c_literal(text):
    """`text` as one C string literal: `"` and `\\` escaped, everything else as it is."""
    bad = [ch for ch in text if ord(ch) < 0x20 or ord(ch) == 0x7F]
    if bad:
        raise EmbedError(f"a control character ({ord(bad[0]):#04x}) can't go into the header")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate_header(assets_dir):
    """The text of web_assets.h for the five files in `assets_dir` (LF, deterministic)."""
    assets_dir = Path(assets_dir)
    parts = [BANNER]
    for file_name, c_name, kind in ASSETS:
        path = assets_dir / file_name
        if not path.is_file():
            raise EmbedError(f"{file_name}: missing (expected {path})")
        # utf-8-sig: a BOM from a Windows editor would land in the icon URI / the first rule
        text = path.read_bytes().decode("utf-8-sig")
        pieces = _svg_pieces(text) if kind == "svg" else _pieces(text, kind, file_name)
        parts.append(f"\n// {file_name}\nstatic const char {c_name}[] =")
        if not pieces:
            parts[-1] += ' "";\n'
            continue
        parts[-1] += "\n" + "\n".join("    " + c_literal(p) for p in pieces) + ";\n"
    return "".join(parts)


def _normalized(path):
    try:
        return path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    except FileNotFoundError:
        return None


def update_header(assets_dir, out, check=False):
    """Regenerates `out`. Returns 0 (up to date or written) or 1 (`check` and stale)."""
    text = generate_header(assets_dir)
    if _normalized(out) == text:
        return 0
    if check:
        print(f"{out} is stale: run python tools/embed_assets.py", file=sys.stderr)
        return 1
    out.write_bytes(text.encode("utf-8"))
    print(f"embed_assets: wrote {out}")
    return 0


def main(argv=None, root=None):
    root = Path(root) if root else Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--assets", type=Path, default=root / ASSETS_DIR)
    parser.add_argument("--out", type=Path, default=root / HEADER)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the header is stale, write nothing")
    args = parser.parse_args(argv)
    try:
        return update_header(args.assets, args.out, args.check)
    except EmbedError as e:
        print(f"embed_assets: error: {e}", file=sys.stderr)
        return 2


def _pre_build(env):
    """PlatformIO pre-script: the header up to date before anything compiles."""
    root = Path(env.subst("$PROJECT_DIR"))
    try:
        update_header(root / ASSETS_DIR, root / HEADER)
    except EmbedError as e:
        sys.stderr.write(f"embed_assets: error: {e}\n")
        env.Exit(1)


try:
    Import("env")  # noqa: F821 -- defined only when PlatformIO / SCons runs this file
except NameError:
    pass  # imported (the tests) or run from the command line
else:
    _pre_build(env)  # noqa: F821

if __name__ == "__main__":
    sys.exit(main())
